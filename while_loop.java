public class while_loop 
{
    public static void main(String []args)
    {
        int i = 1;

        while(i <= 5)
        {
            System.out.println("Hi how are you? " + i);

            int j = 1;
            while(j <=5)
            {
                System.out.println("I am fine. ");

                j++;
            }

            i++;
        }

    }
}
